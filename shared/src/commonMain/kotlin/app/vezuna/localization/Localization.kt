data class PluralForms(val one: String, val other: String)

sealed interface UserText {
    data class Key(val key: L10nKey, val args: List<String> = emptyList()) : UserText
    data class Plural(val key: L10nKey, val quantity: Int, val args: List<String> = emptyList()) : UserText
}

class VitaMessageException(val userText: UserText.Key) : IllegalArgumentException(userText.key.name)

fun message(key: L10nKey, vararg args: Any?): UserText.Key = UserText.Key(key, args.map { it?.toString().orEmpty() })
fun pluralMessage(key: L10nKey, quantity: Int, vararg args: Any?): UserText.Plural = UserText.Plural(key, quantity, args.map { it?.toString().orEmpty() })
fun failMessage(key: L10nKey, vararg args: Any?): Nothing = throw VitaMessageException(message(key, *args))

expect fun deviceLanguageTag(): String

fun Throwable.toUserText(fallback: L10nKey = L10nKey.ACTION_FAILED): UserText = when (this) {
    is VitaMessageException -> userText
    else -> UserText.Key(fallback)
}
