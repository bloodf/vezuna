@Composable
fun vitaText(key: L10nKey, vararg args: Any): String =
    stringResource(stringResources.getValue(key), *args)

@Composable
fun vitaPlural(key: L10nKey, quantity: Int, vararg args: Any): String =
    pluralStringResource(pluralResources.getValue(key), quantity, quantity, *args)

@Composable
fun UserText.resolve(): String = when (this) {
    is UserText.Key -> vitaText(key, *args.toTypedArray())
    is UserText.Plural -> vitaPlural(key, quantity, *args.toTypedArray())
}
